"""Per-language paths shared by the training, validation and inference scripts.

    data/<lang>/      training data (generated by generate_data.py)
    models/<lang>/    trained artifacts: diet_model.pt, word_dict.json, ngram_dict.json,
                      intent_labels.json, entity_labels.json, model_config.json
"""

import json
import os

import torch

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DATA_DIR = os.path.join(ROOT, "data")
MODELS_DIR = os.path.join(ROOT, "models")

# Defaults of the sparse feature extractor (used when a model has no model_config.json)
DEFAULT_MODEL_CONFIG = {
    "word_dict_size": 300,
    "ngram_dict_size": 1000,
    "ngram_overflow_size": 100,
    "ngram_min": 2,
    "ngram_max": 5,
}

