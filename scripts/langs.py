def pick_device(requested: str = "auto") -> str:
    """Resolve the device to run on.

    "auto" uses CUDA only if a kernel actually runs on the GPU: ``torch.cuda.is_available()`` can be
    True with a PyTorch build that has no kernels for the GPU architecture (e.g. an RTX 50xx / sm_120
    with torch 2.5), which fails later with "no kernel image is available". In that case it falls
    back to CPU. The DIET model is small, so CPU inference takes a few milliseconds.
    """
    if requested != "auto":
        return requested
    if not torch.cuda.is_available():
        return "cpu"
    try:
        (torch.ones(2, device="cuda") + 1).sum().item()
        return "cuda"
    except Exception as e:
        print(f"CUDA is available but unusable with torch {torch.__version__} ({str(e).splitlines()[0]}); using CPU.")
        return "cpu"


def load_json(filepath: str):
    """Load a JSON file."""
    try:
        with open(filepath, "r", encoding="utf8") as f:
            return json.load(f)
    except Exception as e:
        print(f"Failed to load {filepath}: {e}")
        raise


def data_dir(lang: str) -> str:
    return os.path.join(DATA_DIR, lang)


def model_dir(lang: str) -> str:
    return os.path.join(MODELS_DIR, lang)


def model_files(lang: str) -> dict:
    """Paths of every artifact needed to run the model of a language."""
    d = model_dir(lang)
    return {
        "model": os.path.join(d, "diet_model.pt"),
        "word_dict": os.path.join(d, "word_dict.json"),
        "ngram_dict": os.path.join(d, "ngram_dict.json"),
        "intent_labels": os.path.join(d, "intent_labels.json"),
        "entity_labels": os.path.join(d, "entity_labels.json"),
        "model_config": os.path.join(d, "model_config.json"),
    }


def data_languages() -> list:
    """Languages with generated training data."""
    if not os.path.isdir(DATA_DIR):
        return []
    return sorted(l for l in os.listdir(DATA_DIR)
                  if os.path.isfile(os.path.join(DATA_DIR, l, "data.yml")))


def trained_languages() -> list:
    """Languages with a trained model."""
    if not os.path.isdir(MODELS_DIR):
        return []
    return sorted(l for l in os.listdir(MODELS_DIR)
                  if os.path.isfile(os.path.join(MODELS_DIR, l, "diet_model.pt")))


def load_model_config(lang: str) -> dict:
    path = model_files(lang)["model_config"]
    if os.path.isfile(path):
        return {**DEFAULT_MODEL_CONFIG, **load_json(path)}
    return dict(DEFAULT_MODEL_CONFIG)
